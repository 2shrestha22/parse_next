import 'dart:io';

/// Writes test/fixtures.g.dart from test/fixtures/*.json, so the golden tests
/// can run in a browser, where dart:io cannot read files.
/// With `--check`, exits 1 instead if the file is out of date.
void main(List<String> args) {
  final root = File.fromUri(Platform.script).parent.parent;
  final dir = Directory('${root.path}/test/fixtures');
  final out = File('${root.path}/test/fixtures.g.dart');

  final files =
      dir
          .listSync()
          .whereType<File>()
          .where((f) => f.path.endsWith('.json'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));

  final buf = StringBuffer()
    ..writeln(
      '// Generated by tool/embed_fixtures.dart; edit the fixtures and '
      'rerun it.',
    )
    ..writeln()
    ..writeln('const fixtures = <String, String>{');
  for (final f in files) {
    final name = f.uri.pathSegments.last;
    final body = f.readAsStringSync();
    if (body.contains("'''")) throw StateError("$name contains '''");
    buf
      ..writeln("  '$name': r'''")
      ..write(body.endsWith('\n') ? body : '$body\n')
      ..writeln("''',");
  }
  buf.writeln('};');

  final generated = buf.toString();
  if (args.contains('--check')) {
    if (!out.existsSync() || out.readAsStringSync() != generated) {
      stderr.writeln(
        '${out.path} is stale; run dart run tool/embed_fixtures.dart',
      );
      exit(1);
    }
    return;
  }
  out.writeAsStringSync(generated);
}
